"""sim_meter — 模拟电表模块。

DL/T 645 多功能电能表从站模拟器：在串口（RS-485）上以从站身份应答主站
（集中器 / CCO / 抄表工具）的 645 帧，补齐工程里"有模拟集中器、有侦听台、
没有模拟电表"的缺口。

支持能力（默认 645-2007，可切 1997）：
- 应答地址：13H 广播读通信地址（FE×6）→ 93H 回表地址；11H 读 DI=04000401H
  （CCO 固件读表地址口径）→ 91H 回表地址；15H 写通信地址。
- 查询时间：11H 读 04000101H（日期及周次 YYMMDDWW）/ 04000102H（时间 hhmmss）；
  08H 广播校时（99×6 广播，无需应答）与 14H 写时间生效到表内时钟。
- 抄表：11H 读 00010000H 正向有功总电能及费率、电压 / 电流 / 瞬时功率等
  常用 DI，数据集可通过接口设置。
- 波特率：17H 更改通信速率（速率特征字单 bit 有效）→ 应答后串口热切换；
  兼容知识库口径 09H。接口层亦可直接切换波特率。
- 重庆即装即采（JZJC）：设备类型（4036 取值，0x10 表 / 0x12 导轨表 /
  0x28 量测开关等）与设备描述符可配置，按 Q/GDW 11612.43（STA 上报事件
  类型 51）与 1376.2 AFN=06H F7 两种结构生成设备信息上送报文。
- 698 采集 OAD 数据集（REQS-0037）：分钟采集任务点 OAD（如 20000201 /
  20010201 / 20000200）可配置应答数据或缺项（不进应答条目，STA 读层按
  任务配置长度补 FF），文件配置 + 运行时 API 两层，API 优先级高于文件；
  未配置 OAD 保持历史行为（不应答）。

设计要点：
- 帧构造 / 切帧复用 parser_lib.adapters.adapter_645（build_frame /
  build_frame_escaped / try_extract），保证构帧与工程解析口径一致。
- 控制码以 DL/T 645-2007 国标为准（17H 更改通信速率）；知识库 645 卡
  将 09H 记为更改通信速率，与国标存在偏差，本模块两者都实现为更改速率。
- 独立模块，不侵入 sim_concentrator / listener 现有流程；REST API 可独立
  运行（python -m sim_meter）或挂载到侦听台。
"""

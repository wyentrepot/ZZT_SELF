@pytest.mark.parametrize("desc,hex_str,fn,afn", _CHONGQING_FRAMES,
                         ids=[f[0] for f in _CHONGQING_FRAMES])
def test_doc_chongqing_frame(adapter, desc, hex_str, fn, afn):
    """重庆市文档示例帧解析测试。

    文档来源: 05.6_重庆.md §4.1~§4.13
    预期: 省份帧使用FT1.2双L格式，适配器可能无法识别(pos3!=0x68)
    """
    raw = _hex(hex_str)
    confidence = adapter.confidence(raw)
    if confidence > 0:
        fr = adapter.decode(raw)
        assert fr.structure == "1376.2"
    else:
        pytest.skip(f"适配器不支持此帧格式(双L FT1.2): {desc}, confidence={confidence}")


